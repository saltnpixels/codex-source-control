import { tmpdir } from 'node:os';
import assert from 'node:assert/strict';
import { mkdtemp, writeFile, readFile, rename, rm } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { resolve, join } from 'node:path';
import { updateStaging } from '../plugins/source-control-proof/git-staging.mjs';
import { getFile } from '../plugins/source-control-proof/git-file.mjs';
import { getStatus } from '../plugins/source-control-proof/git-status.mjs';
const root = await mkdtemp(join(tmpdir(), 'codex-source-control-staging-fixture-')), unborn = await mkdtemp(join(tmpdir(), 'codex-source-control-unborn-fixture-'));
const git = (cwd,...args) => execFileSync('git',['-C',cwd,...args],{encoding:'utf8'});
const write = (path,text) => writeFile(root+'/'+path,text);
const stage = (path,group,action) => updateStaging({repoPath:root,path,group,action});
const svg = size => '<svg xmlns="http://www.w3.org/2000/svg" width="'+size+'" height="'+size+'"><rect width="100%" height="100%" fill="gray"/></svg>';
try {
  git(root,'init','-b','proof');
  for(const path of ['partial.txt','keep.txt','old.txt','delete.txt'])await write(path,'base\n');
  await write('preview.svg',svg(64));git(root,'add','.');git(root,'-c','user.name=Proof','-c','user.email=proof@example.test','commit','-m','Fixture');
  await write('keep.txt','keep staged\n');git(root,'add','keep.txt');
  await write('partial.txt','staged\n');git(root,'add','partial.txt');await write('partial.txt','working\n');
  let status=await stage('partial.txt','unstaged','stage');
  assert(status.staged.some(f=>f.path==='partial.txt'));assert(!status.unstaged.some(f=>f.path==='partial.txt'));
  assert.equal(git(root,'show',':partial.txt'),'working\n');
  status=await stage('partial.txt','staged','unstage');assert(status.unstaged.some(f=>f.path==='partial.txt'));
  assert.equal(await readFile(root+'/partial.txt','utf8'),'working\n');assert.equal(git(root,'show',':keep.txt'),'keep staged\n');
  await write('new [literal].txt','new\n');await stage('new [literal].txt','untracked','stage');await stage('new [literal].txt','staged','unstage');
  assert.equal(await readFile(root+'/new [literal].txt','utf8'),'new\n');
  await rm(root+'/delete.txt');await stage('delete.txt','unstaged','stage');await stage('delete.txt','staged','unstage');
  await assert.rejects(readFile(root+'/delete.txt'),/ENOENT/);
  await rename(root+'/old.txt',root+'/renamed.txt');git(root,'add','old.txt','renamed.txt');await write('renamed.txt','edited rename\n');
  await stage('renamed.txt','unstaged','stage');await stage('renamed.txt','staged','unstage');
  assert.equal(await readFile(root+'/renamed.txt','utf8'),'edited rename\n');await assert.rejects(readFile(root+'/old.txt'),/ENOENT/);
  await write('one.txt','one');await write('two.txt','two');
  await Promise.all([stage('one.txt','untracked','stage'),stage('two.txt','untracked','stage')]);
  status=await getStatus(root);assert(status.staged.some(f=>f.path==='one.txt'));assert(status.staged.some(f=>f.path==='two.txt'));
  await assert.rejects(stage('../outside','untracked','stage'),/inside the checkout/);
  await assert.rejects(stage('partial.txt','staged','stage'),/Invalid staging group/);
  await write('preview.svg',svg(128));git(root,'add','preview.svg');await write('preview.svg',svg(256));
  const view=(group,mode)=>getFile({repoPath:root,path:'preview.svg',group,mode});
  let images=(await view('staged','diff')).images;
  assert.equal(images.length,2);assert(Buffer.from(images[0].dataUrl.split(',')[1],'base64').toString().includes('width="64"'));
  assert(Buffer.from(images[1].dataUrl.split(',')[1],'base64').toString().includes('width="128"'));
  images=(await view('unstaged','source')).images;
  const bytes=await readFile(root+'/preview.svg');assert.equal(images[0].byteSize,bytes.length);assert.equal(Buffer.from(images[0].dataUrl.split(',')[1],'base64').toString(),svg(256));
  await write('large.png',Buffer.alloc(8*1024*1024+1));
  const large=await getFile({repoPath:root,path:'large.png',group:'untracked',mode:'source'});
  assert.equal(large.images[0].byteSize,8*1024*1024+1);assert(!large.images[0].dataUrl);
  git(unborn,'init','-b','unborn');await writeFile(unborn+'/new.txt','keep me');
  await updateStaging({repoPath:unborn,path:'new.txt',group:'untracked',action:'stage'});
  await updateStaging({repoPath:unborn,path:'new.txt',group:'staged',action:'unstage'});
  assert.equal(await readFile(unborn+'/new.txt','utf8'),'keep me');assert((await getStatus(unborn)).untracked.some(f=>f.path==='new.txt'));
  console.log('PASS: stage/unstage, partial staging, literal paths, deletions, renames, unrelated index entries, parallel actions, unborn HEAD, image snapshots, byte sizes and image limits.');
}finally{await Promise.all([rm(root,{recursive:true,force:true}),rm(unborn,{recursive:true,force:true})])}
