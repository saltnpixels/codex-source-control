import { tmpdir } from 'node:os';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, rename, rm, symlink } from 'node:fs/promises';
import { execFileSync, spawn } from 'node:child_process';
import { resolve, join } from 'node:path';
import { createInterface } from 'node:readline';
import { fileURLToPath } from 'node:url';
import { getStatus } from '../plugins/source-control-proof/git-status.mjs';
import { getFile } from '../plugins/source-control-proof/git-file.mjs';
const cwd = await mkdtemp(join(tmpdir(), 'codex-source-control-git-fixture-'));
const git = (...args) => execFileSync('git', ['-C',cwd,...args], { encoding:'utf8' });
try {
  git('init','-b','proof-branch');
  await writeFile(cwd+'/partially staged.txt','base\n');
  await writeFile(cwd+'/old name.txt','rename\n');
  git('add','.');
  git('-c','user.name=Proof','-c','user.email=proof@example.test','commit','-m','Temporary fixture');
  await writeFile(cwd+'/partially staged.txt','base\nstaged\n');git('add','partially staged.txt');
  await writeFile(cwd+'/partially staged.txt','base\nstaged\nunstaged\n');
  await rename(cwd+'/old name.txt',cwd+'/new name.txt');git('add','old name.txt','new name.txt');
  await writeFile(cwd+'/untracked\nfile.txt','new\n');
  const data = await getStatus(cwd);
  assert.equal(data.branch,'proof-branch');
  assert(data.staged.some(f=>f.path==='partially staged.txt'));
  assert(data.unstaged.some(f=>f.path==='partially staged.txt'));
  assert(data.staged.some(f=>f.path==='new name.txt'&&f.originalPath==='old name.txt'));
  assert(data.untracked.some(f=>f.path==='untracked\nfile.txt'));
  const view = (path,group,mode) => getFile({repoPath:cwd,path,group,mode});
  assert.equal((await view('partially staged.txt','staged','source')).text,'base\nstaged\n');
  assert.equal((await view('partially staged.txt','unstaged','source')).text,'base\nstaged\nunstaged\n');
  assert((await view('partially staged.txt','staged','diff')).text.includes('+staged'));
  assert(!(await view('partially staged.txt','staged','diff')).text.includes('+unstaged'));
  assert((await view('partially staged.txt','unstaged','diff')).text.includes('+unstaged'));
  assert.equal((await view('new name.txt','staged','source')).text,'rename\n');
  assert((await view('new name.txt','staged','diff')).text.includes('rename to new name.txt'));
  assert((await view('untracked\nfile.txt','untracked','diff')).text.includes('+new'));
  await writeFile(cwd+'/binary.dat',Buffer.from([0,1,2]));
  assert((await view('binary.dat','untracked','source')).message.includes('Binary'));
  git('add','binary.dat');assert((await view('binary.dat','staged','source')).message.includes('Binary'));
  await symlink(tmpdir(),cwd+'/external-link');
  assert.equal((await view('external-link','untracked','source')).text,tmpdir());
  await writeFile(cwd+'/large.txt','a'.repeat(512*1024+1));
  assert((await view('large.txt','untracked','source')).message.includes('512 KB'));
  await assert.rejects(view('../outside.txt','untracked','source'),/inside the checkout/);
  await assert.rejects(view('missing.txt','untracked','source'),/no longer/);
  const before = git('status','--porcelain=v1','-z');
  await getStatus(cwd);assert.equal(git('status','--porcelain=v1','-z'),before);
  git('checkout','--detach');assert((await getStatus(cwd)).branch.startsWith('Detached HEAD'));
  const codexHome = cwd+'/codex-home'; await mkdir(codexHome);
  await writeFile(codexHome+'/.codex-global-state.json',JSON.stringify({'local-projects':{fixture:{id:'fixture',name:'Fixture project',rootPaths:[cwd]}}}));
  const child=spawn(process.execPath,[fileURLToPath(new URL('../plugins/source-control-proof/server.mjs', import.meta.url))],{cwd,env:{...process.env,CODEX_HOME:codexHome}});
  const pending=new Map();let id=0;
  createInterface({input:child.stdout}).on('line',line=>{const msg=JSON.parse(line);pending.get(msg.id)?.(msg);pending.delete(msg.id)});
  const request=(method,params={})=>new Promise(res=>{const next=++id;pending.set(next,res);child.stdin.write(JSON.stringify({jsonrpc:'2.0',id:next,method,params})+'\n')});
  assert((await request('initialize')).result.capabilities.tools);
  const inventory=(await request('tools/list')).result;
  assert(inventory.tools[0]._meta['openai/ui'].entrypoints.some(e=>e.type==='thread'));
  assert((await request('tools/call',{name:'source_control_panel',arguments:{}})).result.structuredContent.needsCheckout);
  const status=(await request('tools/call',{name:'source_control_panel',arguments:{repoPath:cwd}})).result;
  assert.equal(status.structuredContent.contextSource,'explicit checkout');
  assert.equal(status.structuredContent.checkout,data.checkout);
  assert((await request('resources/read',{uri:inventory.tools[0]._meta.ui.resourceUri})).result.contents[0].text.includes('ui/initialize'));
  assert(inventory.tools[0].icons[0].src.startsWith('data:image/svg+xml'));
  const projectResult=(await request('tools/call',{name:'git_projects',arguments:{}})).result;
  assert(projectResult.structuredContent.projects.some(p=>p.label==='Fixture project'));
  const fileResult=(await request('tools/call',{name:'git_file',arguments:{repoPath:cwd,path:'partially staged.txt',group:'staged',mode:'source'}})).result;
  assert.equal(fileResult.structuredContent.text,'base\nstaged\n');
  child.kill();
  console.log('PASS: staged/working source and diff separation, rename, binary/size handling, path validation, symbolic links, detached HEAD, read-only status, MCP tools/resources and icon.');
}finally{await rm(cwd,{recursive:true,force:true})}
